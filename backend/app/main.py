"""FastAPI service for the Smart Classroom dashboard.

This service reads already-generated pipeline outputs. It does not run
InsightFace or capture camera frames itself.
"""
from __future__ import annotations

import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from fastapi import Depends, FastAPI, Header, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, PlainTextResponse

load_dotenv()

OUTPUT_DIR = Path(os.getenv(
    "CLASSROOM_OUTPUT_DIR",
    str(Path(__file__).resolve().parents[2] / "output"),
)).expanduser()
CLASSROOM_IMAGE_NAME = os.getenv("CLASSROOM_IMAGE_NAME", "classroom_result.jpg")
OCCUPANCY_FILE_NAME = os.getenv("OCCUPANCY_FILE_NAME", "occupancy.txt")
API_KEY = os.getenv("CLASSROOM_API_KEY", "").strip()
ALLOWED_ORIGINS = [
    item.strip()
    for item in os.getenv("CORS_ORIGINS", "http://localhost:5173").split(",")
    if item.strip()
]

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}
ZONE_NAMES = ("BACK_LEFT", "BACK_RIGHT", "FRONT_LEFT", "FRONT_RIGHT")

app = FastAPI(
    title="Smart Classroom API",
    version="1.0.0",
    description="Serves anonymized classroom pipeline outputs and aggregate occupancy data.",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET"],
    allow_headers=["Authorization", "Content-Type"],
)


def optional_api_key(authorization: str | None = Header(default=None)) -> None:
    """Validate a bearer token only when CLASSROOM_API_KEY is configured."""
    if not API_KEY:
        return
    expected = f"Bearer {API_KEY}"
    if authorization != expected:
        raise HTTPException(status_code=401, detail="Invalid or missing API key")


def safe_output_file(filename: str) -> Path:
    """Resolve a filename strictly inside OUTPUT_DIR to prevent path traversal."""
    candidate = (OUTPUT_DIR / filename).resolve()
    root = OUTPUT_DIR.resolve()
    if candidate.parent != root or candidate.suffix.lower() not in IMAGE_EXTENSIONS:
        raise HTTPException(status_code=400, detail="Invalid image name")
    if not candidate.is_file():
        raise HTTPException(status_code=404, detail="Image not found")
    return candidate


def read_report() -> str:
    path = OUTPUT_DIR / OCCUPANCY_FILE_NAME
    if not path.is_file():
        return "Occupancy report is not available yet."
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "Unable to read occupancy report."


def parse_report(report: str) -> dict[str, Any]:
    """Extract common totals and region counts from the text report.

    The parser tolerates different labels so the API can serve reports
    generated by multiple versions of the image-processing script.
    """
    def number(pattern: str, default: int = 0) -> int:
        match = re.search(pattern, report, flags=re.IGNORECASE | re.MULTILINE)
        if not match:
            return default
        try:
            return int(match.group(1))
        except (TypeError, ValueError):
            return default

    total = number(r"(?:total\s+persons?\s+detected|total\s+occupancy|occupancy|persons?\s+detected)\s*[:=]\s*(\d+)")
    zones: dict[str, int] = {}
    aliases = {
        "BACK_LEFT": r"(?:BACK[_ ]LEFT|BACK LEFT|LEFT BACK)",
        "BACK_RIGHT": r"(?:BACK[_ ]RIGHT|BACK RIGHT|RIGHT BACK)",
        "FRONT_LEFT": r"(?:FRONT[_ ]LEFT|FRONT LEFT|LEFT FRONT)",
        "FRONT_RIGHT": r"(?:FRONT[_ ]RIGHT|FRONT RIGHT|RIGHT FRONT)",
    }
    for zone, label in aliases.items():
        zones[zone] = number(label + r"\s*[:=]\s*(\d+)")
    # Support older reports that use Left/Right and Row 1..4.
    if not any(zones.values()):
        left = number(r"Left Side\s*[:=]\s*(\d+)")
        right = number(r"Right Side\s*[:=]\s*(\d+)")
        row_values = [
            number(rf"Row\s*{index}\s*[:=]\s*(\d+)")
            for index in range(1, 5)
        ]
        if any(row_values):
            zones = dict(zip(ZONE_NAMES, row_values))
        elif left or right:
            zones = {
                "BACK_LEFT": 0,
                "BACK_RIGHT": 0,
                "FRONT_LEFT": left,
                "FRONT_RIGHT": right,
            }
    if total == 0 and any(zones.values()):
        total = sum(zones.values())
    return {
        "total_occupancy": total,
        "regions": zones,
        "active_regions": sum(1 for value in zones.values() if value > 0),
    }


@app.get("/api/health", dependencies=[Depends(optional_api_key)])
def health() -> dict[str, Any]:
    return {
        "status": "ok",
        "output_directory_exists": OUTPUT_DIR.is_dir(),
        "output_directory": str(OUTPUT_DIR),
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }


@app.get("/api/dashboard", dependencies=[Depends(optional_api_key)])
def dashboard() -> dict[str, Any]:
    report = read_report()
    stats = parse_report(report)
    image_path = OUTPUT_DIR / CLASSROOM_IMAGE_NAME
    image_available = image_path.is_file()
    return {
        **stats,
        "camera_status": "online" if image_available else "offline",
        "processing_status": "ready" if OUTPUT_DIR.is_dir() else "unavailable",
        "classroom_image": CLASSROOM_IMAGE_NAME if image_available else None,
        "image_path": str(image_path) if image_available else None,
        "updated_at": datetime.fromtimestamp(
            image_path.stat().st_mtime, tz=timezone.utc
        ).isoformat() if image_available else None,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }


@app.get("/api/classroom-image", dependencies=[Depends(optional_api_key)])
def classroom_image() -> FileResponse:
    path = safe_output_file(CLASSROOM_IMAGE_NAME)
    return FileResponse(path, media_type="image/jpeg", filename=path.name)


@app.get("/api/images", dependencies=[Depends(optional_api_key)])
def list_images() -> dict[str, Any]:
    if not OUTPUT_DIR.is_dir():
        return {"images": []}
    images = sorted(
        item.name for item in OUTPUT_DIR.iterdir()
        if item.is_file() and item.suffix.lower() in IMAGE_EXTENSIONS
    )
    return {"images": images}


@app.get("/api/images/{image_name}", dependencies=[Depends(optional_api_key)])
def get_image(image_name: str) -> FileResponse:
    path = safe_output_file(image_name)
    media_type = {
        ".png": "image/png",
        ".webp": "image/webp",
    }.get(path.suffix.lower(), "image/jpeg")
    return FileResponse(path, media_type=media_type, filename=path.name)


@app.get("/api/occupancy-report", dependencies=[Depends(optional_api_key)])
def occupancy_report() -> PlainTextResponse:
    return PlainTextResponse(read_report(), media_type="text/plain; charset=utf-8")
